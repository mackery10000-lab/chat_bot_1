"""인물 배경과 일상 반응. 아이템·단서·출입·엔딩 상태를 변경하지 않는다."""


def character_mood(npc, flags):
    if npc == "explorer":
        return "호기심을 즐기며 항상 유쾌하고 호의적"
    if npc == "elder":
        return "표를 돌려받아 안도함" if flags.get("ticket_returned") else "기억이 흐릿하고 약간 까탈스러우나 정중한 상대를 반김"
    if npc == "cleaner":
        return "청소 중에도 차분하고 친절하게 응대"
    if npc == "attendant":
        return "도움에 감사하며 부드럽게 협조" if flags.get("door_open") else "불안을 숨기며 예민하고 방어적으로 응대"
    if npc == "driver":
        return "시간의 흐름에 놀랐지만 증거를 받아들여 협조" if flags.get("year_proven") else "냉정하고 권위적이며 증거 없이 판단을 바꾸지 않음"
    return ""


